#!/usr/bin/env python3
"""Packs the VR controllers' prompt icons (Kenney Input Prompts 1.5A, CC0: Meta Quest and Valve Index) for Sly 2's VR mod.

Usage: python3 -P tools/pack_vr_prompts.py --zip kenney_input-prompts_1.5.zip [--check]

Writes assets/prompts/prompts_vr.png and Sly2-Release/vrprompt_rects.inc (the rect of each physical control's icon
per controller family, in vrprofile.h's Ctl order then the two sticks). It reuses tools/pack_prompts.py's verified
archive, cell layout and colour bleed, and leaves that script's atlases untouched. Needs Pillow (as pack_prompts.py).
"""
import argparse, hashlib, pathlib, sys, zipfile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pack_prompts as pp  # noqa: E402

# Order == vrprofile.h Ctl (A B X Y TriggerL TriggerR GripL GripR StickClickL StickClickR Menu PadR), then the left
# and right sticks (movement). None: the control has no icon on that controller.
SLOTS = ['a', 'b', 'x', 'y', 'trigger_left', 'trigger_right', 'grip_left', 'grip_right', 'stick_click_left',
         'stick_click_right', 'menu', 'trackpad_right', 'stick_left', 'stick_right']
Q = 'Meta Quest/Double/'
I = 'Valve Index/Double/'
FAMILIES = {
    # Meta Quest Touch (and the Quest 3's Touch Plus): no right trackpad
    'quest': [Q + 'quest_button_a.png', Q + 'quest_button_b.png', Q + 'quest_button_x.png', Q + 'quest_button_y.png',
              Q + 'quest_trigger_left.png', Q + 'quest_trigger_right.png', Q + 'quest_grip_left.png',
              Q + 'quest_grip_right.png', Q + 'quest_stick_l_press.png', Q + 'quest_stick_r_press.png',
              Q + 'quest_button_menu.png', None, Q + 'quest_stick_l.png', Q + 'quest_stick_r.png'],
    # Valve Index: X / Y are the left hand's A / B; Menu and PadR the trackpads squeezed. Kenney's Index set has no
    # grip icon: the Quest's grips stand in (the same squeeze, a similar shape).
    'index': [I + 'index_button_a.png', I + 'index_button_b.png', I + 'index_button_a.png', I + 'index_button_b.png',
              I + 'index_lt.png', I + 'index_rt.png', Q + 'quest_grip_left.png', Q + 'quest_grip_right.png',
              I + 'index_stick_l_press.png', I + 'index_stick_r_press.png', I + 'index_track_press.png',
              I + 'index_track_press.png', I + 'index_stick_l.png', I + 'index_stick_r.png'],
}
HEIGHT = 4 * pp.STRIDE   # 576: 7 x 4 cells


def main():
    root = pathlib.Path(__file__).resolve().parent.parent
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument('--zip', type=pathlib.Path, required=True)
    p.add_argument('--check', action='store_true', help='verify the committed outputs instead of writing')
    a = p.parse_args()
    data = a.zip.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != pp.ZIP_SHA256:
        sys.exit(f'{a.zip}: sha256 {digest} does not match the pinned Kenney 1.5 release {pp.ZIP_SHA256}')
    z = zipfile.ZipFile(a.zip)
    names = []
    for fam in FAMILIES.values():
        for n in fam:
            if n and n not in names:
                names.append(n)
    atlas, rects = pp.pack(z, names, HEIGHT)
    png = pp.png(atlas)
    lines = ['// Generated by tools/pack_vr_prompts.py from Kenney Input Prompts 1.5A (CC0). Do not edit.',
             f'// The icons of prompts_vr.png ({atlas.size[0]} x {atlas.size[1]}): x, y, w, h (y down), w 0: none.',
             f'constexpr int kVrPromptAtlasW = {atlas.size[0]}, kVrPromptAtlasH = {atlas.size[1]};',
             f'constexpr int kVrPromptSlots = {len(SLOTS)};   // vrprofile.h Ctl_*, then the left and right sticks',
             'constexpr int kVrPromptRects[2][kVrPromptSlots][4] = {']
    for fam, icons in FAMILIES.items():
        cells = ', '.join('{%d, %d, %d, %d}' % rects[n] if n else '{0, 0, 0, 0}' for n in icons)
        lines.append(f'    {{{cells}}},   // {fam}')
    lines.append('};')
    inc = ('\n'.join(lines) + '\n').encode()
    outs = {root / 'assets/prompts/prompts_vr.png': png, root / 'Sly2-Release/vrprompt_rects.inc': inc}
    stale = []
    for path, content in outs.items():
        if a.check:
            if not path.exists() or path.read_bytes() != content:
                stale.append(str(path))
        else:
            path.write_bytes(content)
            print(f'wrote {path} ({len(content)} bytes)')
    if stale:
        print('stale: ' + ', '.join(stale))
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
